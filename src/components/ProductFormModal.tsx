/**
 * IMPORTANT ARCHITECTURE NOTE
 *
 * This form is a catalog/product-definition editor.
 * It must NOT be used as the authoritative inventory ledger.
 *
 * In production:
 * - SKU/barcode uniqueness must be enforced by the backend/database.
 * - Stock changes should go through inventory transactions.
 * - Product IDs should be generated by the backend.
 * - Prices/money should be validated server-side using decimal/numeric types.
 * - AI extraction is untrusted input and must be reviewed/validated.
 */

